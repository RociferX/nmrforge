def _axis_traces(real: np.ndarray, axis: int) -> np.ndarray:
    """Expand the spectrum along the axis into (n_trace, axis_len), which is applicable to any
    dimension."""
    moved = np.moveaxis(np.asarray(real, dtype=float), axis, -1)
    return moved.reshape(-1, moved.shape[-1])


def _trace_indices_fixed(
    real: np.ndarray, axis: int, threshold: float = 0.0
) -> tuple[list[int], list[int]]:
    """Return the signal trace index and strongest point position along axis (patch29ff
    vectorization, consistent results)."""
    traces = _axis_traces(real, axis)
    mag = np.abs(traces)
    peaks = np.argmax(mag, axis=-1)
    maxima = mag[np.arange(traces.shape[0]), peaks]
    keep = maxima > threshold
    idx = np.nonzero(keep)[0]
    return [int(i) for i in idx], [int(peaks[i]) for i in idx]


def _grid_step(values: tuple[float, ...]) -> float:
    """The step size of the equidistant grid (the median of adjacent differences); less than 2
    points returns 0."""
    if len(values) < 2:
        return 0.0
    diffs = sorted(
        float(values[i + 1]) - float(values[i]) for i in range(len(values) - 1)
    )
    return float(diffs[len(diffs) // 2])


def _refine_steps(coarse_step: float, final_step: float) -> list[float]:
    """A sequence of refinements from coarse step size to target step size (approximately 1/3
    decreasing, with the last level being the target step size)."""
    steps: list[float] = []
    s = float(coarse_step)
    while True:
        nxt = s / 3.0
        if nxt <= final_step:
            steps.append(float(final_step))
            break
        steps.append(nxt)
        s = nxt
    return steps


def _refine_window(center: float, prev_step: float, new_step: float) -> list[float]:
    """Refinement window around centre: Cover +/-prev_step/2, press new_step to pick the point."""
    half = prev_step / 2.0
    n = int(math.ceil(half / new_step))
    return [center + k * new_step for k in range(-n, n + 1)]


def rotate_real(
    complex_arr: np.ndarray, axis: int, p0: float, p1: float
) -> np.ndarray:
    """Memory frequency domain rotation takes the real part, the same convention as nmrPipe PS:
    phase(k) = p0 + p1·k/(n-1), point-by-point complex multiplication exp(i·phase), takes the
    real part (= -di semantics)."""
    arr = np.asarray(complex_arr, dtype=np.complex128)
    # 0.2.199-patch29dp: When p1=0, phase has nothing to do with k, scalar rotation (avoiding the
    # point-by-point complex multiplication of the entire axis ramp array -- 3D NUS The main
    # overhead of large array ~50 times of candidate scoring).
    if abs(p1) < 1e-9:
        c = float(np.cos(np.deg2rad(p0)))
        s = float(np.sin(np.deg2rad(p0)))
        return arr.real * c - arr.imag * s
    n = arr.shape[axis]
    k = np.arange(n, dtype=float)
    ramp = np.exp(1j * np.deg2rad(p0 + p1 * k / max(n - 1, 1)))
    shape = [1] * arr.ndim
    shape[axis] = n
    return np.real(arr * ramp.reshape(shape))


def _gather_slices(
    rows: np.ndarray, starts: np.ndarray, ends: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    """Each row [start,end) slices are collected into an equal-width matrix (patch29ff, out-of-
    bounds NaN mask)."""
    n_rows, width = rows.shape
    maxlen = int(np.max(ends - starts)) if n_rows else 0
    if maxlen <= 0:
        return np.zeros((n_rows, 0)), np.zeros((n_rows, 0), dtype=bool)
    cols = np.arange(maxlen)[None, :]
    offs = starts[:, None] + cols
    valid = (offs < ends[:, None]) & (offs < width)
    idx = np.where(valid, offs, 0)
    return rows[np.arange(n_rows)[:, None], idx], valid


def _median_rows(gathered: np.ndarray, valid: np.ndarray) -> np.ndarray:
    """Median number of valid values by row (equivalent to np.median row by row, the last digit
    is allowed to be 1e-16)."""
    counts = valid.sum(axis=1)
    if counts.size == 0:
        return np.zeros(0)
    s = np.sort(np.where(valid, gathered, np.inf), axis=1)
    k1 = (counts - 1) // 2
    k2 = counts // 2
    vals = np.take_along_axis(s, np.stack([k1, k2], axis=1), axis=1)
    return 0.5 * (vals[:, 0] + vals[:, 1])


def _window_nets(
    real: np.ndarray,
    axis: int,
    indices: list[int],
    positions: list[int],
    *,
    half_width: int | None = None,
) -> list[float]:
    """The net absorption of each window signature (pos+neg)/total (same formula as the old
    _window_metric). The positive and negative judgments are made by first leveling the baseline
    -- taking the mean median value of the baseline area on both sides of the peak (+/-6..18
    points) as the baseline level, and then subtracting the baseline from the window to divide
    it into positive and negative; the overall offset of the baseline (positive or negative) no
    longer contaminates the net absorption (0.2.175 user plan). half_width(points) Adjustable
    window half-width (0.2.199-patch29dn, Plan B test): Default 5 is consistent with the old
    behaviour; normalisation by line width/resolution (high resolution window is larger) can
    eliminate "+/-5 points covering too large line width at low resolution, resulting in phase
    optimal offset" (sampleI F1 at 431 points preview 105°, 1024 points final spectrum optimal
    90°)."""
    hw = 5 if half_width is None else max(int(half_width), 1)
    moved = np.moveaxis(real, axis, -1)
    traces = moved.reshape(-1, moved.shape[-1])
    nets: list[float] = []
    for index, peak in zip(indices, positions):
        if index < 0 or index >= traces.shape[0]:
            continue
        n = traces.shape[1]
        left_base = traces[index, max(0, peak - 3 * hw - 3) : max(0, peak - hw - 1)]
        right_base = traces[
            index, min(n, peak + hw + 2) : min(n, peak + 3 * hw + 4)
        ]
        if left_base.size >= 4 and right_base.size >= 4:
            baseline = 0.5 * (
                float(np.median(left_base)) + float(np.median(right_base))
            )
        else:
            baseline = float(np.median(traces[index]))
        profile = traces[index, max(0, peak - hw) : peak + hw + 1]
        peak_h = float(np.max(np.abs(profile)))
        # Baseline is flattened only when the relative peak height shift is significant (>= 1%);
        # baseline is flattened and the spectrum remains zero-bounded.
        if peak_h > 1e-12 and abs(baseline) / peak_h >= 0.01:
            profile = profile - baseline
        positive = float(np.clip(profile, 0.0, None).sum())
        negative = float(np.clip(profile, None, 0.0).sum())
        total = float(np.abs(profile).sum())
        nets.append((positive + negative) / total if total else 0.0)
    return nets


def _window_nets_from_rows(
    rows: np.ndarray,
    positions: list[int],
    *,
    half_width: int | None = None,
) -> list[float]:
    """Lock the net absorption of each trace line (patch29ff vectorization, equivalent rewriting;
    baseline translation only acts on valid points within the peak window, out-of-boundary zero
    filling does not participate in translation)."""
    hw = 5 if half_width is None else max(int(half_width), 1)
    n_rows = rows.shape[0]
    if n_rows == 0:
        return []
    width = rows.shape[1]
    peaks = np.asarray(positions, dtype=int)
    ls = np.maximum(0, peaks - 3 * hw - 3)
    le = np.maximum(0, peaks - hw - 1)
    lmat, lvalid = _gather_slices(rows, ls, le)
    rs = np.minimum(width, peaks + hw + 2)
    re = np.minimum(width, peaks + 3 * hw + 4)
    rmat, rvalid = _gather_slices(rows, rs, re)
    lcount = lvalid.sum(axis=1)
    rcount = rvalid.sum(axis=1)
    ok = (lcount >= 4) & (rcount >= 4)
    lmed = np.zeros(n_rows)
    rmed = np.zeros(n_rows)
    if ok.any():
        lmed[ok] = _median_rows(lmat[ok], lvalid[ok])
        rmed[ok] = _median_rows(rmat[ok], rvalid[ok])
    baseline = np.where(ok, 0.5 * (lmed + rmed), np.median(rows, axis=1))
    ps = np.maximum(0, peaks - hw)
    pe = peaks + hw + 1
    pmat, pvalid = _gather_slices(rows, ps, pe)
    profile = np.where(pvalid, pmat, 0.0)
    peak_h = np.max(np.abs(profile), axis=1)
    cond = (
        (peak_h > 1e-12)
        & (np.abs(baseline) / np.maximum(peak_h, 1e-30) >= 0.01)
    )
    shifted = np.where(pvalid, pmat - baseline[:, None], 0.0)
    profile = np.where(cond[:, None], shifted, profile)
    positive = np.clip(profile, 0.0, None).sum(axis=1)
    negative = np.clip(profile, None, 0.0).sum(axis=1)
    total = np.abs(profile).sum(axis=1)
    nets = np.where(total > 0, (positive + negative) / total, 0.0)
    return [float(v) for v in nets]


def score_locked_memory(
    rows: np.ndarray,
    positions: list[int],
    p0: float,
    p1: float,
    *,
    sign_mode: str = "uniform",
    net_half_width: int | None = None,
) -> float:
    """Lock trace row scoring (0.2.199-patch29dp): only rotate the locked row, no longer perform a
    duplicate rotation on the entire array for each candidate (3D NUS (256,256,586) Each axis
    search 23-25s -> sub-second level)."""
    real = rotate_real(rows, -1, p0, p1)
    nets = _window_nets_from_rows(
        real, positions, half_width=net_half_width
    )
    if not nets:
        return 50.0
    if sign_mode == "mixed":
        score = 50.0 * (float(np.median(np.abs(nets))) + 1.0)
        strong = [nn for nn in nets if abs(nn) > 0.35]
        if strong:
            pos = sum(1 for nn in strong if nn > 0)
            neg = sum(1 for nn in strong if nn < 0)
            if pos >= 1 and neg >= 1:
                return score
            return score * 0.7
        return score
    return 50.0 * (float(np.median(nets)) + 1.0)


def score_axis_memory(
    complex_arr: np.ndarray,
    axis: int,
    p0: float,
    p1: float,
    indices: list[int],
    positions: list[int],
    *,
    sign_mode: str = "uniform",
    net_half_width: int | None = None,
) -> float:
    """Candidate phase score (0-100). sign_mode="mixed" (HNCACB and other positive and negative
    peaks coexist): Absorption = the median of |net absorption of each window| -- Zhengfeng/Even
    negative peaks can get high scores; then require the coexistence of positive and negative
    strong and weak peaks (missing a symbol penalty (Positive peak preference resolves +/-180
    ambiguities)."""
    real = rotate_real(complex_arr, axis, p0, p1)
    nets = _window_nets(
        real, axis, indices, positions, half_width=net_half_width
    )
    if not nets:
        return 50.0
    if sign_mode == "mixed":
        score = 50.0 * (float(np.median(np.abs(nets))) + 1.0)
        strong = [n for n in nets if abs(n) > 0.35]
        if strong:
            pos = sum(1 for n in strong if n > 0)
            neg = sum(1 for n in strong if n < 0)
            if pos >= 1 and neg >= 1:
                return score
            return score * 0.7
        return score
    median = float(np.median(nets))
    return 50.0 * (median + 1.0)


def _lock_discrete_traces(
    complex_arr: np.ndarray,
    axis: int,
    *,
    prominence_min: float = 2.5,
    window: int = 10,
    max_duty: float = 0.5,
    threshold_pct: float = 95.0,
    discrete: bool = True,
) -> tuple[list[int], list[int]]:
    """Lock the "discrete peak" trace for phase modulation scoring. It is consistent with manual
    nmrDraw's "pick discrete peak phase modulation": the discrete peak selection (discrete=True)
    threshold is set to the low quantile (default 95, the central large group will be raised
    99.5 quantile to eliminate discrete peaks), and then the peak shape sharpness is used to
    filter --- peak position +/-window >= the proportion of the half-high point (duty) <=
    max_duty And the peak top is significant (prominence) relative to the low quantile of the
    local background. The central mixed peak cluster (dense peak cluster) occupies a large
    proportion of the window and is excluded; when there are no discrete peaks, the threshold is
    gradually lowered, and finally all traces are rolled back. This option is only used for
    mixed (HNCACB and other positive and negative coexistence) experiments --- Uniform spectrum
    can use the old lock (99.5 quantile of all strong traces), discrete filtering will change
    the trace set to d103 and other band biases 180° (VM d103 regression calibration)."""
    real0 = np.real(complex_arr)
    if not discrete:
        noise_old = float(np.std(real0[:80, :40])) if real0.size else 0.0
        thr_old = max(float(np.percentile(real0, 99.5)), noise_old * 5.0)
        out = _trace_indices_fixed(real0, axis, thr_old)
        if out[0]:
            return out
        return _trace_indices_fixed(real0, axis, -1.0)
    moved = np.moveaxis(real0, axis, -1)
    traces = moved.reshape(-1, moved.shape[-1])
    n = moved.shape[-1]
    noise = float(np.std(real0[:80, :40])) if real0.size else 0.0
    for pct in (threshold_pct, 75.0):
        threshold = max(float(np.percentile(real0, pct)), noise * 5.0)
        indices: list[int] = []
        positions: list[int] = []
        for i in range(traces.shape[0]):
            mag = np.abs(traces[i])
            peak = int(np.argmax(mag))
            if float(mag[peak]) <= threshold:
                continue
            half = 0.5 * float(mag[peak])
            lo = max(0, peak - window)
            hi = min(n, peak + window + 1)
            seg = mag[lo:hi]
            if seg.size == 0:
                continue
            duty = float(np.mean(seg >= half))
            if duty > max_duty:
                continue
            bg = float(np.percentile(seg, 25.0))
            if float(mag[peak]) / (bg + 1e-12) >= prominence_min:
                indices.append(i)
                positions.append(peak)
        if indices:
            return indices, positions
    return _trace_indices_fixed(real0, axis, -1.0)


def _subsampled_score_memory(
    real: np.ndarray, axis: int, k: int = 500, group: str = "even"
) -> float:
    """Take a half-group subsampling of top-K strong traces with peak height along axis, and
    evaluate in-memory phase_quality (same index as the old scheme _subsampled_score, except
    that the input is a memory array)."""
    from core.qc import phase_quality

    moved = np.moveaxis(real, axis, -1)
    traces = moved.reshape(-1, moved.shape[-1])
    peak_mag = np.max(np.abs(traces), axis=-1)
    order = np.argsort(peak_mag)[::-1][:k]
    selected = order[0::2] if group == "even" else order[1::2]
    if selected.size == 0:
        return 0.0
    return float(phase_quality.evaluate(traces[selected]).score)


def _subsampled_score_rows(
    rows: np.ndarray, k: int = 500, group: str = "even"
) -> float:
    """Locks the top-K half-set of subsampled scores for trace rows (0.2.199-patch29dp, row
    variant)."""
    from core.qc import phase_quality

    peak_mag = np.max(np.abs(rows), axis=-1)
    order = np.argsort(peak_mag)[::-1][:k]
    selected = order[0::2] if group == "even" else order[1::2]
    if selected.size == 0:
        return 0.0
    return float(phase_quality.evaluate(rows[selected]).score)


